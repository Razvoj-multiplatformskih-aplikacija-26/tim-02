Unit _unit(Champion champion, {int stars = 1, List<Item> items = const []}) =>
    Unit.parse(champion, stars: stars, items: items).valueOrNull!;

Placement _at(int row, int column, Champion champion, {int stars = 1, List<Item> items = const []}) => Placement(
  unit: _unit(champion, stars: stars, items: items),
  position: HexPosition.parse(row, column).valueOrNull!,
);

Lineup _board(List<Placement> placements) =>
    placements.fold(const Lineup.empty(), (lineup, placement) => lineup.place(placement).valueOrNull!);
